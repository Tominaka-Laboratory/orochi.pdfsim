def _run_refinement(self, conditions: list, optimizer: dict = None, verbose=False):
    """
    Internal helper to initialize and execute the specified optimizer with refinement conditions.

    Args:
        conditions (list): A list of refinement condition dictionaries generated by `_get_*_refinement_params`.
        optimizer (dict, optional): Configuration for the optimization solver.
            Supported keys:
                - "type" (str): Optimizer algorithm type ('lls' for Least Squares, 'bayes'/'optuna' for Bayesian Optimization). Defaults to 'lls'.
                - "fit_min" (float): Minimum r-value (Å) for PDF fitting. Defaults to 1.5.
                - "fit_max" (float): Maximum r-value (Å) for PDF fitting. Defaults to 15.0.
                - "n_trials" (int): Number of optimization trials (for Bayesian optimization). Defaults to 50.

    Returns:
        dict: Dictionary containing 'best_scores' and 'best_params' resulting from the refinement.
    """
    default_config = {"type": "lls", "fit_min": 1.5, "fit_max": 15.0, "n_trials": 50}
    if optimizer is None:
        opt_config = default_config
    else:
        opt_config = {**default_config, **optimizer}

    # Safe extraction without mutating the original input dict
    opt_type = opt_config.pop("type", "lls")

    # Optimization type
    if opt_type == "lls":
        from orochi.fit.pdf.least_squares import Optimizer as LeastSquaresOptimizer
        self.optimizer = LeastSquaresOptimizer()
    elif opt_type in ["bayes", "ba", "optuna"]:
        from orochi.fit.pdf.bayes import Optimizer as BayesOptimizer
        self.optimizer = BayesOptimizer()
    else:
        raise ValueError(f"Unsupported optimizer type: {opt_type}")

    # Study name
    self.optimizer.study_name = opt_config.pop("study_name", self.study_name)

    #Remaining parameters
    for key, val in opt_config.items():
        self.optimizer[key] = val

    self.optimizer.simulators = [self]
    self.optimizer.work_dir = self.work_dir
    self.optimizer.set_obs_data(self.obs_x, self.obs_y)
    self.optimizer["continue_study"] = True

    self.optimizer._set_refine_conditions(conditions)
                
    if not verbose:
        optuna.logging.set_verbosity(optuna.logging.WARNING)
        
    self.optimizer()

    if not verbose:
        optuna.logging.set_verbosity(optuna.logging.INFO)

    self.optimizer._reset_refine_conditions(conditions)
    
    best_scores = getattr(self.optimizer, "best_scores", {})
    best_params = getattr(self.optimizer, "best_params", {})
    return {"best_scores": best_scores, "best_params": best_params}


def _make_indexed_optimize(
    self,
    indices: Optional[list] = None,
    element_types: Optional[list] = None,
    values: Optional[np.ndarray] = None,
) -> np.ndarray:
    values_arr = np.asarray(values)
    opts = np.ones(values_arr.shape, dtype=bool)

    # 1. Filter by site indices
    if indices is not None:
        mask_ids = np.zeros(values_arr.shape, dtype=bool)
        mask_ids[indices] = True
        opts &= mask_ids

    # 2. Filter by element types
    if element_types is not None:
        symbols = np.asarray(self.phase["symbol"])
        mask_ele = np.isin(symbols, element_types)

        # Broadcast mask_ele across trailing dimensions when opts has 2 or more dimensions
        if opts.ndim > mask_ele.ndim:
            mask_ele = mask_ele[(...,) + (None,) * (opts.ndim - mask_ele.ndim)]

        opts &= mask_ele

    return opts

def _get_all_refinement_params(self, **kwargs):

    ordered_conds = {}

    for key, params in kwargs.items():
        order = functions_and_params.get(key, {}).get("order", 2)
        if order not in ordered_conds:
            ordered_conds[order] = []

        func = functions_and_params.get(key, {}).get("func", None)
        if func is None: continue

        if params is None:
            res = func(self)
        else:
            res = func(self, **params)
        ordered_conds[order].extend(res)

    cond_list = []
    for order in sorted(ordered_conds.keys()):
        cond_list.extend(ordered_conds[order])       
    return cond_list

def refine(self, **kwargs):
    """
    see simulator
    """
    conditions = _get_all_refinement_params(self, **kwargs)
    optimizer = kwargs.get("optimizer")
    return _run_refinement(self, conditions, optimizer)



##use atoms
def _get_use_atoms_params(self,
                          site_indices: list = None, 
                          element_types: list = None):
    
    # 1. Identify elements to move to subphase from element_types (elements retained in main phase)
    if element_types is not None:
        if isinstance(element_types, str):
            element_types = [element_types]
        
        symbols = np.array(self.phase["symbol"])
        mask = np.isin(symbols, element_types)  # True = elements retained in main phase
        symbols_to_subphase = np.unique(symbols[~mask]).tolist()
    else:
        symbols_to_subphase = None

    # 2. Identify site indices to move to subphase from site_indices (sites retained in main phase)
    if site_indices is not None:
        indices = np.arange(self.phase["xyz"].shape[0])
        mask = np.isin(indices, site_indices)   # True = sites retained in main phase
        sites_to_subphase = indices[~mask].tolist()
    else:
        sites_to_subphase = None

    # 3. Define condition (split on forward, merge on backward)
    conditions = [
        {
            "name": "split_into_subphase",
            "order": 0,
            "forward": lambda si=sites_to_subphase, et=symbols_to_subphase: 
                        self.phase.split_into_subphase(site_indices=si, element_types=et, subphase_key="subphase"),
            "backward": lambda: self.phase.merge_subphase(),      
        },
    ]
    return conditions

##Lattice
def _get_lattice_refinement_params(self, 
                            a=0., 
                            b=0., 
                            c=0., 
                            alpha=0., 
                            beta=0., 
                            gamma=0.):
    changes = np.array([a, b, c, alpha, beta, gamma]).astype(float)
    conditions = [
        {
            "name": "lattice_constraints",
            "func": lambda: self.phase.set_lattice_constraints()         
            },
        {"module":self.phase,
            "key":"lattice",               
            "attr":"min", 
            "val": lambda c=changes: self.phase["lattice"] - c
            },
        {"module":self.phase, 
            "key":"lattice", 
            "attr":"max", 
            "val": lambda c=changes: self.phase["lattice"] + c
            },
        {"module":self.phase,
            "key":"lattice",               
            "attr":"fit", 
            "val": lambda c=changes: np.where(c > 0.0, True, False),
            },
        ]
    return conditions
    
def refine_lattice_parameters(self, a=0., b=0., c=0., alpha=0., beta=0., gamma=0., optimizer: dict = None):
    """
    Refine unit cell lattice parameters under symmetry constraints.

    Args:
        a, b, c (float): Maximum allowed change for axis lengths (in Å). Set to 0.0 to fix.
        alpha, beta, gamma (float): Maximum allowed change for lattice angles (in degrees). Set to 0.0 to fix.
        optimizer (dict, optional): Optimizer settings dictionary (e.g., {"type": "lls", "fit_min": 1.5, "fit_max": 15.0}).

    Returns:
        dict: Optimization result containing 'best_scores' and 'best_params'.
    """
    conditions = _get_lattice_refinement_params(self, a, b, c, alpha, beta, gamma)
    return _run_refinement(self, conditions, optimizer)


