# simulator params

def _get_simulator_refinement_params(self, scale=0., delta1=0., delta2=0., qbroad=0., qdamp=0.):
    target_params = {
        "scale": float(scale),
        "delta1": float(delta1),
        "delta2": float(delta2),
        "qbroad": float(qbroad),
        "qdamp": float(qdamp)
    }
    boundary_min = {
        "scale": 0.7,
        "delta1": 0.,
        "delta2": 0.,
        "qbroad": 0.,
        "qdamp": 0.
    }
    boundary_max = {
        "scale": 1.3,
        "delta1": 0.1,
        "delta2": 0.1,
        "qbroad": 0.1,
        "qdamp": 0.1
    }

    conditions = []
    for key, change in target_params.items():
        if change == 0.: continue

        b_min = boundary_min.get(key)
        b_max = boundary_max.get(key)

        conditions += [            
            {
                "module": self,
                "key": key,                
                "attr": "fit",  
                "val": lambda: True
            },
            {
                "module": self,
                "key": key,                
                "attr": "min", 
                # Bind k, c, mn via default arguments
                "val": lambda k=key, c=change, mn=b_min: self[k] - c if self[k] - c > mn else mn
            },
            {
                "module": self,
                "key": key,                
                "attr": "max", 
                # Bind k, c, mx via default arguments
                "val": lambda k=key, c=change, mx=b_max: self[k] + c if self[k] + c < mx else mx
            }
        ]
    return conditions

def refine_simulation_parameters(self, scale=0., delta1=0., delta2=0., qbroad=0., qdamp=0., optimizer: dict = None):
    """
    Refine instrumental and simulation-specific parameters.

    Args:
        scale (float): Maximum change for scale factor. Lower bound is capped at 0.7 to avoid unphysical scaling.
        delta1 (float): Maximum change for low-r peak broadening (1/r term).
        delta2 (float): Maximum change for low-r peak broadening (1/r^2 term).
        qbroad (float): Maximum change for instrumental resolution broadening.
        qdamp (float): Maximum change for instrumental resolution damping.
        optimizer (dict, optional): Optimizer settings dictionary.

    Returns:
        dict or list: Optimization result or condition list.
    """
    conditions = _get_simulator_refinement_params(self, scale, delta1, delta2, qbroad, qdamp)
    return _run_refinement(self, conditions, optimizer)


